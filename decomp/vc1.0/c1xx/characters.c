/* Original 0x3cf50..0x3cf80. */
void initialize_lead_bytes(void)
{
    static CPINFO console_codepage; /* original 0x97bf0 */
    if (GetCPInfo(GetConsoleCP(), &console_codepage))
        mark_lead_byte_ranges(console_codepage.LeadByte);
    else
        mark_lead_byte_ranges((unsigned char *)"\xf0\xf1\xf2\xf3\xf4\xf5\xf6\xf7\xf8\xf9");
}

