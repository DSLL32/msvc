/* Original 0x3cef0..0x3cf49. */
void mark_lead_byte_ranges(unsigned char *ranges)
{
    unsigned start, end, c;
    for (;;) {
        start = *ranges++;
        if (!start)
            return;
        end = *ranges++;
        if (!end)
            return;
        if (end >= start)
            for (c = start; c <= end; ++c)
                character_class[c] = CC_LEAD_BYTE;
    }
}
