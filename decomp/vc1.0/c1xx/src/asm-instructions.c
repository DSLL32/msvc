int asm_operand_class; /* original 0x8c010, distinct from address-mode 0x8c00c */
typedef char AsmInstructionProperties_size[(sizeof(AsmInstructionProperties) == 8) ? 1 : -1];

/* Original 0x7d8b8..0x7d915, stdcall4. Classifier canonical IDs
   and alias opcode bytes index0..229; selecting one restarts operand zero. */
void __stdcall select_asm_opcode(short opcode)
{
    if (!(target_cpu_mask & asm_instruction_properties[opcode].processors))
        report_syntax_error(416, interned_name);
    asm_operation = opcode;
    asm_operand_class = asm_instruction_properties[opcode].operand_class;
    asm_operand = asm_operands;
    asm_operands[0].address = asm_addresses;
}
