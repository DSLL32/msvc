#!/usr/bin/env python3
"""Reassemble recorded routines with named callees and contextual C data.

Data definitions are hand-maintained in the owning C sources. An unknown data
reference is an error: add a suitably typed definition and its address mapping
before regenerating. This script never copies or emits original data sections.
"""
from pathlib import Path
import json, re
from collections import defaultdict
import capstone
from binary import PE, COFF, archive, u16, u32
from importlib.machinery import SourceFileLoader
wt=SourceFileLoader('wine_tool','wine-tool.py').load_module()
pe=PE(wt.TC/'bin/LINK.EXE')
cfg=json.loads(Path('functions.json').read_text())
runtime=json.loads(Path('runtime.json').read_text())
data_symbols=json.loads(Path('data-symbols.json').read_text())
md=capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_32);md.detail=True
fixups=set();p=pe.offset(pe.base+u32(pe.data,pe.optional+136));end=p+u32(pe.data,pe.optional+140)
while p<end:
    page,size=u32(pe.data,p),u32(pe.data,p+4)
    if not size:break
    for q in range(p+8,p+size,2):
        value=u16(pe.data,q)
        if value>>12==3:fixups.add(pe.base+page+(value&4095))
    p+=size
records={r['start']:r for r in runtime}
cfg['driver']=[r for r in cfg['driver'] if r.get('implementation')!='stub-asm' or r['start'] not in records]
for r in cfg['driver']:records[r['start']]=r
new_stubs={};used_funcs={n[1:] for n in cfg.get("c_stub_references",[])};current_funcs=set();current_data=set()
def function(address):
    rec=records.get(address)
    if rec is None:
        rec=dict(name='_unreconstructed_%08x'%address,start=address,end=address+1,implementation='stub-asm')
        records[address]=rec;new_stubs[address]=rec
    name=rec['name']
    if not re.fullmatch(r'_[A-Za-z_][A-Za-z_0-9]*',name):
        raise ValueError('unsupported function symbol '+name)
    used_funcs.add(name[1:]);current_funcs.add(name[1:]);return name[1:]
def data(address):
    choices=[r for r in data_symbols if r['address']<=address<r['address']+r['size']]
    if not choices:raise ValueError('define encountered data at %08x in its contextual C source'%address)
    rec=min(choices,key=lambda r:r['size'])
    current_data.add(rec['name']);return rec['name'],address-rec['address']
def pointer(address):
    if 0x17000<=address<0x5bc22:return function(address),0
    return data(address)
def expr(name,offset):return name+(' + 0x%x'%offset if offset else '')
outputs=defaultdict(list);dependencies=defaultdict(lambda:[set(),set()])
for rec in cfg['driver']:
    if rec.get('implementation')!='assembly':continue
    owner=rec['source'];start,end=rec['start'],rec['end']
    instructions=list(md.disasm(pe.read(start,end-start),start))
    assert instructions and instructions[-1].address+instructions[-1].size==end,rec['name']
    body=[];current_funcs=set();current_data=set()
    for ins in instructions:
        op=ins.op_str;mn=ins.mnemonic
        if mn.startswith(('rep ','repe ','repne ')) or mn in ('movsb','movsd','stosb','stosd','scasb','scasd'):op=''
        if ins.group(capstone.CS_GRP_JUMP) or ins.group(capstone.CS_GRP_CALL):
            if ins.operands and ins.operands[0].type==capstone.x86.X86_OP_IMM:
                target=ins.operands[0].imm
                op=('label_%08x'%target if start<=target<end else function(target))
        for fixup in sorted(fixups):
            if ins.address<=fixup<ins.address+ins.size:
                target=u32(pe.read(fixup,4),0);name,offset=pointer(target);term=expr(name,offset)
                literal='0x%x'%target
                assert literal in op,(hex(ins.address),op,literal)
                op=op.replace(literal,term if '[' in op else 'OFFSET '+term)
        if mn=='push' and ins.operands[0].type==capstone.x86.X86_OP_IMM and not op.startswith('OFFSET '):op='dword ptr '+op
        op=op.replace('ptr ds:','ptr ').replace('ptr es:','ptr ')
        body+=['    label_%08x:'%ins.address,'        %s%s'%(mn,' '+op if op else '')]
    outputs[owner].append('/* %s; original [%08x,%08x). */\n_declspec(naked) void %s(void)\n{\n    __asm {\n%s\n    }\n}\n'%(rec.get('abi','cdecl; assembly preserves original argument registers/stack'),start,end,rec['name'][1:],'\n'.join(body)))
    dependencies[owner][0].update(current_funcs);dependencies[owner][1].update(current_data)
def write_changed(path,value):
    path=Path(path)
    if not path.exists() or path.read_text()!=value:path.write_text(value)
head='/* Generated by lift.py: symbolic instructions; data lives in the including C file. */\n'
for owner in {r.get('source') for r in cfg['driver'] if r.get('source')}:
    if '#include \"'+owner.replace('.c','-asm.inc')+'\"' not in Path(owner).read_text():continue
    funcs,variables=dependencies[owner]
    local={r['name'] for r in data_symbols if r['owner']==owner}
    decls='\n'.join('extern void %s(void);'%n for n in sorted(funcs))+'\n'
    decls+='\n'.join('extern unsigned char %s[];'%n for n in sorted(variables-local))+'\n'
    write_changed(owner.replace('.c','-asm.inc'),head+decls+'\n'.join(outputs[owner]))
# Only stubs referenced by reconstructed functions remain. Data is defined on
# encounter, so there are no speculative pointers copied from unused sections.
allstubs={r['start']:r for r in cfg['driver'] if r.get('implementation')=='stub-asm' and r['name'][1:] in used_funcs}
allstubs.update(new_stubs)
write_changed('assembly-stubs.c',head+'\n'.join('_declspec(naked) void %s(void) { __asm { int 3 } }'%r['name'][1:] for r in sorted(allstubs.values(),key=lambda r:r['start'])))
cfg['driver']=[r for r in cfg['driver'] if r.get('implementation')!='stub-asm' or r['start'] in allstubs]
for addr,rec in sorted(new_stubs.items()):cfg['driver'].append(rec)
write_changed('functions.json',json.dumps(cfg,indent=2)+'\n')
print('%d symbolic routines; %d named trap stubs; contextual data only'%(sum(map(len,outputs.values())),len(allstubs)))
