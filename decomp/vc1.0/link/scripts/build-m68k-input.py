#!/usr/bin/env python3
"""Explicit deterministic COFF fixture-input generation; never executes a target.

COFF layouts follow shipped NTIMAGE.H and the Microsoft specification. Target
machine0x268, relocation names and legacy section bits follow native LINK
analysis and original validation. Opcode encodings follow Motorola M68000PRM.
The resulting bytes are test input, not reconstruction implementation.
"""
import argparse
from pathlib import Path
import struct,json,hashlib


def make_object(variant):
    if variant=='minimal':
        sections=[('.text',bytes.fromhex('4e75'),0x60000020,[])]
        symbols=[('_main',0,1)]
    else:
        # Startup uses an A5-relative jump-table call: it needs no runtime fixup.
        # Other CODE resources carry absolute code/data pointers, with loader
        # prologues and fixup streams generated by the original linker.
        sections=[
            ('.text',bytes.fromhex('4ead00004e754e75'),0x60000020,[(2,2,8)]),
            ('.text2',bytes.fromhex('4eb9000000002039000000004e75'),0x60000020,
             [(2,3,11),(8,4,10)]),
            ('.text3',bytes.fromhex('70074e75'),0x60000020,[]),
            ('.data',bytes.fromhex('0000002a00000000'),0xc0000040,[(4,4,4)])
        ]
        symbols=[('_main',0,1),('___Init32BitLoadSeg',6,1),
                 ('_helper',0,2),('_leaf',0,3),('_value',0,4)]
    cursor=20+40*len(sections)
    raw_offsets=[]
    for name,data,flags,relocations in sections:
        raw_offsets.append(cursor)
        cursor+=len(data)
    relocation_offsets=[]
    for name,data,flags,relocations in sections:
        relocation_offsets.append(cursor if relocations else 0)
        cursor+=10*len(relocations)
    symbol_offset=cursor
    strings=bytearray(4)
    symbol_data=bytearray()
    symbol_layout=[]
    for index,(name,value,section) in enumerate(symbols):
        encoded=name.encode('ascii')
        if len(encoded)>8:
            field=struct.pack('<II',0,len(strings))
            strings+=encoded+b'\0'
        else:
            field=encoded.ljust(8,b'\0')
        symbol_data+=struct.pack('<8sIhHBB',field,value,section,0x20 if sections[section-1][2]&0x20 else 0,2,0)
        symbol_layout.append(dict(index=index,name=name,value=value,section=section))
    struct.pack_into('<I',strings,0,len(strings))
    header=struct.pack('<HHIIIHH',0x268,len(sections),0,symbol_offset,len(symbols),0,0)
    section_headers=bytearray()
    layout=[]
    for i,(name,data,flags,relocations) in enumerate(sections):
        section_headers+=struct.pack('<8sIIIIIIHHI',name.encode(),0,0,len(data),raw_offsets[i],relocation_offsets[i],0,len(relocations),0,flags)
        layout.append(dict(name=name,raw_offset=raw_offsets[i],raw_bytes=len(data),flags=flags,code_or_data_hex=data.hex(),relocation_offset=relocation_offsets[i],relocations=[dict(offset=a,symbol=b,type=c) for a,b,c in relocations]))
    raw=b''.join(data for name,data,flags,relocations in sections)
    relocations=b''.join(struct.pack('<IIH',*r) for name,data,flags,records in sections for r in records)
    result=header+section_headers+raw+relocations+symbol_data+strings
    return result,dict(variant=variant,machine=0x268,header_bytes=20,section_header_bytes=40,symbol_offset=symbol_offset,symbol_record_bytes=18,timestamp=0,sections=layout,symbols=symbol_layout,bytes=len(result),sha256=hashlib.sha256(result).hexdigest())


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--variant',choices=['minimal','reloc-loader'],required=True)
    p.add_argument('--output',type=Path,required=True)
    o=p.parse_args()
    data,layout=make_object(o.variant)
    o.output.parent.mkdir(parents=True,exist_ok=True)
    o.output.write_bytes(data)
    o.output.with_suffix('.layout.json').write_text(json.dumps(layout,indent=2)+'\n')
    print(o.output,len(data),layout['sha256'])

if __name__=='__main__':
    main()
