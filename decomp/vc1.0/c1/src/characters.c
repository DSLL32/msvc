static CPINFO console_codepage; /* original 0x65e48 */
static unsigned char fallback_lead_bytes[] = {
    0xf0, 0xf1, 0xf2, 0xf3, 0xf4, 0xf5, 0xf6, 0xf7, 0xf8, 0xf9, 0
};

/* Original 0x2d4b0..0x2d4e0. */
void initialize_lead_bytes(void)
{
    if (GetCPInfo(GetConsoleCP(), &console_codepage))
        mark_lead_byte_ranges(console_codepage.LeadByte);
    else
        mark_lead_byte_ranges(fallback_lead_bytes);
}

